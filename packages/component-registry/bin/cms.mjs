#!/usr/bin/env node
import process from "node:process";
import { error } from "node:console";
import { runCli } from "../dist/cli.js";
const codes = new Set([
  "CMS_USAGE",
  "CMS_ARGUMENT_INVALID",
  "CMS_ARGUMENT_REQUIRED",
  "CMS_COMMIT_REQUIRED",
  "CMS_COMMIT_INVALID",
  "CMS_COMMIT_MISMATCH",
  "CMS_FRAMEWORK_INVALID",
  "CMS_REGISTRY_OUTSIDE_ROOT",
  "CMS_TSCONFIG_INVALID",
  "CMS_TYPECHECK_FAILED",
  "CMS_REGISTRY_EXPORT_INVALID",
  "CMS_MANIFEST_INVALID",
  "CMS_MANIFEST_HASH_MISMATCH",
  "CMS_CODE_INDEX_HASH_MISMATCH",
  "CMS_SERVICE_TOKEN_INVALID",
  "CMS_URL_INVALID",
  "CMS_TIMEOUT_INVALID",
  "CMS_DEPLOYMENT_HASH_TIMEOUT",
  "CMS_MANIFEST_REGISTER_FAILED",
  "CMS_REGISTRY_NAME_INVALID",
  "CMS_REGISTRY_PROP_INVALID",
  "CMS_REGISTRY_NAME_DUPLICATE",
  "CMS_REGISTRY_METADATA_INVALID",
  "CMS_REGISTRY_SOURCE_MISSING",
  "CMS_SOURCE_GRAPH_LIMIT",
  "CMS_SOURCE_ALIAS_CYCLE",
  "CMS_SOURCE_DEFINITION_UNSUPPORTED",
  "CMS_SOURCE_DEFINITION_AMBIGUOUS",
  "CMS_SOURCE_IMPLEMENTATION_UNRESOLVED",
  "CMS_SOURCE_IMPLEMENTATION_EXTERNAL",
  "CMS_SOURCE_IMPLEMENTATION_NOT_EXPORTED",
  "CMS_SOURCE_IMPLEMENTATION_MISMATCH",
]);
try {
  await runCli(process.argv.slice(2));
} catch (failure) {
  const code = failure instanceof Error ? failure.message.split(":")[0] : undefined;
  error(codes.has(code) ? code : "CMS_CLI_FAILURE");
  process.exitCode = 1;
}
